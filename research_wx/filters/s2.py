import sys; sys.path.insert(0,sys.argv[2]); from pol import *
def G(met,pos): return [r for r in R if r["metric"]==met and r["pos"]==pos]
LN=G("low","need"); LH=G("low","holds"); HH=G("high","holds"); HN=G("high","need")
print("Lows need"); print(row("baseline",policy(LN)))
for s in (.05,.06,.07,.08): print(row(f" min spread {s}",policy(LN,lambda r,s=s:r["sp"]>=s-1e-9)))
for p in (.95,.92,.90,.85): print(row(f" max price {p}",policy(LN,lambda r,p=p:r["px"]<=p+1e-9)))
print(row(" skip falling tr1>=1",policy(LN,lambda r:r["tr1"]<1)))
print(row(" skip falling tr3>=2",policy(LN,lambda r:r["tr3"]<2)))
print(row(" only before 16 local",policy(LN,lambda r:r["lhr"]<16)))
print("\nLows holds"); print(row("baseline",policy(LH)))
for s in (.06,.08): print(row(f" min spread {s}",policy(LH,lambda r,s=s:r["sp"]>=s-1e-9)))
print(row(" skip falling tr3>=2",policy(LH,lambda r:r["tr3"]<2)))
print(row(" only before 13 local",policy(LH,lambda r:r["lhr"]<13)))
print("\nHighs holds"); print(row("baseline",policy(HH)))
for h in (14,15,16,17): print(row(f" wait until local {h}:00",policy(HH,lambda r,h=h:r["lhr"]>=h)))
print(row(" wait until not rising (tr1<1)",policy(HH,lambda r:r["tr1"]<1)))
print(row(" wait until tr1<1 and lhr>=14",policy(HH,lambda r:r["tr1"]<1 and r["lhr"]>=14)))
print(row(" skip room0",policy(HH,lambda r:r["room"]>=1)))
print(row(" wait tr1<1 & room>=1",policy(HH,lambda r:r["tr1"]<1 and r["room"]>=1)))
for s in (.06,.08): print(row(f" min spread {s}",policy(HH,lambda r,s=s:r["sp"]>=s-1e-9)))
print("\nHighs need (paper)"); print(row("baseline",policy(HN)))
print(row(" gap>=3",policy(HN,lambda r:r["gap"]>=3)))
print(row(" gap>=3 & lhr>=15",policy(HN,lambda r:r["gap"]>=3 and r["lhr"]>=15)))
for h in (15,16): print(row(f" wait until {h}",policy(HN,lambda r,h=h:r["lhr"]>=h)))
print(row(" wait not rising",policy(HN,lambda r:r["tr1"]<1)))
print(row(" wait not rising & gap>=3",policy(HN,lambda r:r["tr1"]<1 and r["gap"]>=3)))
